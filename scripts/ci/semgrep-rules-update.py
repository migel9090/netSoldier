#!/usr/bin/env python3
"""Regenerate scripts/ci/semgrep-rules.txt, the pinned Semgrep rule set.

    scripts/ci/semgrep-rules-update.py COMMIT

The SAST gate used to run the registry packs p/default, p/security-audit
and p/owasp-top-ten, fetched from semgrep.dev on every run. Their content
changes whenever the registry does, so an unchanged tree could turn red (or
green) overnight, and the job needed semgrep.dev at run time. The gate now
runs the same rules from a pinned commit of github.com/semgrep/semgrep-rules
(the repository the registry publishes them from): this script asks the
registry which rules the three packs hold today, maps each rule id to its
file at COMMIT, and writes the list. scripts/ci/tools.sh fetches exactly
those files at exactly that commit.

Left out on purpose: rules under the AGPL-3.0 (the packs include some from
trailofbits/semgrep-rules), because the project accepts no AGPL dependency.
The others are under the Semgrep Rules License v1.0, which allows use for
one's own internal purposes but no redistribution: the repository lists the
files, it never copies them.

After running it: put COMMIT into SEMGREP_RULES_COMMIT in scripts/ci/tools.sh
and run `task scan:sast` to see what the new rules find.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import yaml

PACKS = ("default", "security-audit", "owasp-top-ten")
REGISTRY = "semgrep.dev"
REPO = "semgrep/semgrep-rules"
OUT = Path(__file__).resolve().parent / "semgrep-rules.txt"
# Rule-id prefixes (top-level directory of the rule's origin) that are not
# taken, with the reason printed into the list.
EXCLUDED = {"trailofbits.": "AGPL-3.0 (trailofbits/semgrep-rules)"}


def pack_ids(pack: str) -> list[str]:
    # HTTPS only, to the one fixed host; the path comes from PACKS.
    url = f"https://{REGISTRY}/c/p/{pack}"
    argv = ["curl", "-fsSL", "--proto", "=https", "--max-time", "120", url]
    out = subprocess.run(argv, check=True, capture_output=True).stdout  # noqa: S603
    return [r["id"] for r in yaml.safe_load(out)["rules"]]


def tree(commit: str) -> list[str]:
    out = subprocess.run(  # noqa: S603
        ["gh", "api", f"repos/{REPO}/git/trees/{commit}?recursive=1"],  # noqa: S607
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    data = json.loads(out)
    if data.get("truncated"):
        sys.exit("the tree listing is truncated; cannot map every rule")
    return [
        e["path"]
        for e in data["tree"]
        if e["type"] == "blob"
        and e["path"].endswith((".yaml", ".yml"))
        and not e["path"].startswith(".")
    ]


def main() -> int:
    if len(sys.argv) != 2 or len(sys.argv[1]) != 40:
        sys.exit(__doc__.split("\n\n")[1])
    commit = sys.argv[1]
    by_stem = {p.rsplit(".", 1)[0].replace("/", ".").lower(): p for p in tree(commit)}
    ids = sorted({i for p in PACKS for i in pack_ids(p)})
    files: set[str] = set()
    missing: list[str] = []
    excluded = 0
    for rule in ids:
        if any(rule.startswith(x) for x in EXCLUDED):
            excluded += 1
            continue
        parts = rule.split(".")
        hit = next(
            (
                by_stem[s]
                for n in range(len(parts) - 1, 0, -1)
                if (s := ".".join(parts[:n]).lower()) in by_stem
            ),
            None,
        )
        if hit:
            files.add(hit)
        else:
            missing.append(rule)
    if missing:
        print("rules in the packs without a file at this commit:", *missing, sep="\n  ")
        return 1
    header = [
        "# The Semgrep rules the SAST gate runs (scripts/ci/iac-gate.py semgrep):",
        f"# files of github.com/{REPO} at SEMGREP_RULES_COMMIT in scripts/ci/tools.sh.",
        f"# Generated by scripts/ci/semgrep-rules-update.py for commit {commit}",
        f"# from the registry packs {', '.join('p/' + p for p in PACKS)}:",
        (
            f"# {len(ids)} rules, {excluded} left out "
            f"({'; '.join(f'{k}* {v}' for k, v in EXCLUDED.items())}), {len(files)} files."
        ),
        "# Do not edit by hand; regenerate.",
    ]
    OUT.write_text("\n".join([*header, *sorted(files)]) + "\n")
    print(f"{OUT}: {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
